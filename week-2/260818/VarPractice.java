// Practice creating variables and printing
public class VarPractice {
    public static void main(String[] args) {
        int var1 = 5;
        double var2 = 10.5;
        int var3 = 1;
        double var4 = 3.4;
        char var5 = 'd';
        boolean var6 = false;

        int numOne = 2;
        int numTwo = 35;
        int middleOne = (numOne + numTwo)/2;
        double middleTwo = (numOne + numTwo)/2.0;

        System.out.println(var1);
        System.out.println(var2);
        System.out.println("var3 = " + var3);
        System.out.println("var4 = " + var4);
        System.out.println("var5 = " + var5);
        System.out.println("var6 = " + var6);
        System.out.println("middleOne=" + middleOne);
        System.out.println("middleTwo=" + middleTwo);
    }
}