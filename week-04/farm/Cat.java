// Implements a class with methods specific to dogs
public class Cat {
    // Method to print sound cat makes
    public void speak() {
        System.out.println("meow");
    }
    // Method to print name of cat
    public void sayName() {
        System.out.println("My name is Felix");
    }
    // Make cat jump
    public void jump() {
        System.out.print("Jumping...");
    }
}